"""LaTeX value macros and tables for both reports (reports/build/generated/), written from pipeline results."""
from __future__ import annotations

import numpy as np
import pandas as pd



def _tab(path, colspec, header, rows, caption=None, label=None, size="\\small"):
    lines = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    lines += [" & ".join(str(c) for c in r) + " \\\\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def write_latex(R, p, t):
    """Write reports/build/generated/values.tex (one \\vName macro per value) and the table files."""
    G = R.gen
    with open(G / "values.tex", "w") as fh:
        fh.write("% generated by src/python/stcool/pipeline.py -- do not edit\n")
        for k, v in sorted(R.macros.items()):
            fh.write(f"\\newcommand{{\\v{k}}}{{{v}}}\n")
    f2 = lambda x, d=2: f"{x:.{d}f}"
    fr = t["fr"]
    _tab(G / "tab_frontier.tex", "rrrrrc", ["Target $\\alpha$", "$N$ (rpm)", "$E$ (kWh)", "OPT pass (\\%)", "VAL pass (\\%) [95\\% CI]", "Rule met"],
         [[f"{100 * r.alpha:.1f}\\%", f2(r.rpm, 1), f2(r.expected_energy_kWh, 3), f2(100 * r.opt_pass), f"{100 * r.val_pass:.2f} [{100 * r.val_ci_lo:.2f}--{100 * r.val_ci_hi:.2f}]",
           "yes" if r.val_meets_alpha_lb else "no"] for r in fr.itertuples()])
    leg = t["leg"]
    _tab(G / "tab_designs.tex", "lrrrrr", ["Design", "$N$ (rpm)", "$\\dot m_{cmd}$ (kg/s)", "$E$ (kWh)", "P(pass) (\\%) [95\\% CI]", "Rule met"],
         [[r.design.replace("v2/v3", "V2/V3").replace("v2 ", "V2 ").replace("v3 ", "V3 "), f2(r.rpm, 1), f2(r.m_cmd, 2), f2(r.mean_energy_kWh, 3),
           f"{100 * r.pass_frac:.2f} [{100 * r.ci_lo:.2f}--{100 * r.ci_hi:.2f}]", "yes" if r.meets_rule else "no"] for r in leg.itertuples()])
    cdf = t["cdf"]
    _tab(G / "tab_cases.tex", "lrrrrrrr", ["Case", "$N$", "$\\dot m$", "$UA_{eff}$ (W/K)", "$T_L(t_f)$ (K)", "Peak $T_J$ (K)", "$\\tau_J$ (s)", "$E$ (kWh)"],
         [[r.case, f2(r.rpm, 1 if r.rpm % 1 else 0), f2(r.mdot, 2), f2(r.UA_eff_W_K, 1), f2(r.T_L_tf_K, 3), f2(r.peak_T_J_K, 1), f2(r.tau_jacket_s, 1), f2(r.energy_kWh, 3)]
          for r in cdf.itertuples()])
    rom = t["rom"]
    _tab(G / "tab_rom.tex", "lrrrrrr", ["Case", "$\\dot m$ (kg/s)", "$UA$ (W/K)", "$\\dot m C_p$ (W/K)", "$\\tau_J/t_f$", "Full (K)", "Reduced $-$ full (K)"],
         [[r.case.replace("M_J", "$M_J$"), f2(r.mdot, 2), f2(r.UA_W_K, 0), f2(r.mCp_W_K, 0), f"{r.tau_jacket_over_tf:.3f}", f2(r.TL_full_K, 2), f"{r.error_K:+.2f}"] for r in rom.itertuples()])
    sc = t["sc"]
    _tab(G / "tab_scenarios.tex", "lrrrrrr", ["Scenario", "$e_N$", "$e_M$", "$T_L(t_f)$ (K)", "Fixed P (\\%)", "Adaptive P (\\%)", "Re-opt.\\ $E$ (kWh)"],
         [[r.scenario.split(" (")[0], f"{r.eN:.3f}", f"{r.eM:.3f}", f2(r.T_L_tf_recommended_K, 2), f2(100 * r.fixed_recommended_pass, 1), f2(100 * r.adaptive_pass, 1),
           "--" if np.isnan(r.reoptimised_expected_energy_kWh) else f2(r.reoptimised_expected_energy_kWh, 3)] for r in sc.itertuples()])
    a = t["ascan"]
    _tab(G / "tab_adaptive_scan.tex", "rrrrrr", ["$N_1$ (rpm)", "$t_{obs}$ (s)", "$\\delta_{cal}$ (K)", "$\\delta$ used (K)", "CAL pass (\\%)", "CAL mean $E$ (kWh)"],
         [[("\\textbf{%.0f}" if r.selected else "%.0f") % r.rpm1, f"{r.t_obs_s:.0f}",
           "--" if np.isnan(r.delta_calibrated_K) else f2(r.delta_calibrated_K, 3), "--" if np.isnan(r.delta_calibrated_K) else f2(r.delta_K, 2),
           "--" if np.isnan(r.delta_calibrated_K) else f2(100 * r.cal_pass, 2),
           "infeasible" if np.isnan(r.delta_calibrated_K) else f2(r.cal_mean_energy_kWh, 3)] for r in a.itertuples()])
    av = t["ad_val"]
    _tab(G / "tab_adaptive_val.tex", "lrrrrrrr", ["Stage", "$n$", "$\\delta$ (K)", "P(pass) (\\%) [95\\% CI]", "LB$_{95}$ (\\%)", "Mean $E$", "P95 $E$", "Capped (\\%)"],
         [[r.stage.split(" (")[0], f"{r.n:,}", f2(r.delta, 2), f"{100 * r.pass_frac:.2f} [{100 * r.pass_ci_lo:.2f}--{100 * r.pass_ci_hi:.2f}]",
           f2(100 * r.pass_lb95_one_sided, 2), f2(r.mean_E, 3), f2(r.p95_E, 2), f2(100 * r.frac_speed_capped, 2)] for r in av.itertuples()])
    rob = t["rob"]
    _tab(G / "tab_adaptive_robust.tex", "llrrr", ["Test", "Setting", "$\\delta$ (K)", "P(pass) (\\%)", "Mean $E$ (kWh)"],
         [[r.test, r.setting, f2(r.delta_K, 3), f2(100 * r.pass_frac, 2), f2(r.mean_energy_kWh, 3)] for r in rob.itertuples()])
    conv = t["conv"]
    _tab(G / "tab_convergence.tex", "rrrr", ["$\\Delta t$ (s)", "$T_L(t_f)$ (K)", "Max trajectory error (K)", "Observed order"],
         [[f"{r.dt_s:g}", f"{r.T_liquid_tf_K:.6f}", f"{r.max_traj_error_K:.2e}", "--" if np.isnan(r.observed_order) else f2(r.observed_order, 2)] for r in conv.itertuples()])
    loc = t["loc"]
    _tab(G / "tab_local.tex", "llrrr", ["Input", "Step", "$\\Delta T_L$ low (K)", "$\\Delta T_L$ high (K)", "Swing (K)"],
         [[r.parameter.replace("U_ref", "$U_{ref}$").replace("M_J", "$M_J$").replace("T_0", "$T_0$"), r.perturbation.replace("+/-", "$\\pm$").replace("%", "\\%").replace("m2", "m\\textsuperscript{2}"),
           f"{r.delta_low_K:+.3f}", f"{r.delta_high_K:+.3f}", f"{r.swing_K:.3f}"] for r in loc.itertuples()])
    sob = t["sobol"]
    _tab(G / "tab_sobol.tex", "llrrr", ["Design", "Input", "$S_1$", "95\\% CI", "$S_T$"],
         [[r.design, r.input.replace("U_ref", "$U_{ref}$").replace("M_J", "$M_J$").replace("T_0", "$T_0$"), f"{max(r.S1, 0):.3f}",
           f"{max(r.S1_ci_lo, 0):.3f}--{r.S1_ci_hi:.3f}", f"{max(r.ST, 0):.3f}"] for r in sob.itertuples()])
    au = t["audit"]
    _tab(G / "tab_audit.tex", "lrrlrr", ["Stage", "$N$ (rpm)", "Data", "Requirement", "P(pass) (\\%)", "$E$ (kWh)"],
         [[r.stage.replace("OPT: ", "").replace(" (speed rounded up to 5 rpm)", ", speed rounded up").replace("continuous ", ""), f2(r.rpm, 2), r.dataset,
           ("$\\hat p \\geq$ " + f"{100 * float(r.requirement.split('>= ')[1]):.2f}\\%") if r.requirement.startswith("sample") else "LB$_{95} \\geq$ 95\\%",
           f2(100 * r.pass_frac, 2), f2(r.expected_energy_kWh, 3)]
          for r in au.itertuples()])
    xc = t["xc"]
    if xc is not None:
        fmt = lambda v, q: (f"{v:.2e}" if abs(v) < 1e-3 and v != 0 else (f"{v:.4f}" if abs(v) < 10 else f"{v:.4f}"))
        _tab(G / "tab_crosscheck.tex", "lrrl", ["Quantity", "Python", "Octave", "Type"],
             [[r.quantity.replace("|", "$|$").replace("%", "\\%").replace("T_L", "$T_L$").replace("T_J", "$T_J$"), fmt(r.python, r.quantity), fmt(r.octave, r.quantity),
               "deterministic" if r.type == "deterministic" else "Monte Carlo"] for r in xc.itertuples()])
    D = R.data
    def tex(x):
        try:
            x = f"{float(x):g}" if not isinstance(x, bool) else x
        except (TypeError, ValueError):
            pass
        return (str(x).replace("%", "\\%").replace("_", "\\_").replace("m3", "m\\textsuperscript{3}").replace("m2", "m\\textsuperscript{2}").replace("<=", "$\\leq$")
                .replace("< 1", "$<$ 1").replace(" C;", "~$^{\\circ}$C;").replace("N\\_P", "$N_P$").replace("0.3-0.5", "0.3--0.5")
                .replace("300-370", "300--370").replace("0.05-0.50", "0.05--0.50").replace("4.18 to", "4.18 to"))
    pr = pd.read_csv(D / "inputs/parameters.csv")
    sym = {"V": "$V$", "rho_L": "$\\rho_L$", "Cp_L": "$C_{p,L}$", "T_0": "$T_0$", "T_in": "$T_{in}$", "A": "$A$", "U_ref": "$U_{ref}$",
           "t_f": "$t_f$", "Cp_C": "$C_{p,C}$", "rho_C": "$\\rho_C$", "N_P": "$N_P$", "M_J": "$M_J$", "N_ref": "$N_{ref}$",
           "mdot_ref": "$\\dot m_{ref}$", "e_N": "$e_N$", "e_M": "$e_M$", "D": "$D$", "eta_ag": "$\\eta_{ag}$", "dP_ref": "$\\Delta P_{ref}$",
           "eta_p": "$\\eta_p$", "m_max": "$\\dot m_{max}$", "N range": "$N$", "T_target": "$T_{target}$"}
    _tab(G / "tab_parameters.tex", "lllp{4.3cm}p{4.3cm}", ["Symbol", "Value", "Unit", "Description", "Classification"],
         [[sym.get(r.symbol, tex(r.symbol)), tex(r.value), tex(r.unit), tex(r.description), tex(r.classification)] for r in pr.itertuples()])
    eqc = pd.read_csv(D / "deterministic/equipment_and_process_checks.csv")
    _tab(G / "tab_equipment.tex", "p{6.2cm}rlp{5.0cm}", ["Check", "Value", "Unit", "Comment"],
         [[tex(r.check).replace("D/T", "$D/T$").replace("M\\_J", "$M_J$").replace("T\\_J", "$T_J$").replace("Re = 2 m/(pi T mu)", "$Re = 2\\dot m/(\\pi T\\mu)$"),
           (f"{r.value:,.0f}" if r.value >= 1000 else (f"{r.value:.2f}" if r.value < 100 else f"{r.value:.1f}")), tex(r.unit), tex(r.comment)] for r in eqc.itertuples()])
    ds = pd.read_csv(D / "inputs/datasets.csv")
    _tab(G / "tab_datasets.tex", "lrrrp{7.4cm}", ["Set", "Seed", "$n$", "Noise seed", "Single purpose"],
         [[r.dataset, r.seed, f"{r.n:,}", "--" if pd.isna(r.noise_seed) or r.noise_seed == "" else int(r.noise_seed), tex(r.purpose)] for r in ds.itertuples()])
    eb = t["eb"]
    _tab(G / "tab_ebal.tex", "lrr", ["Quantity", "Baseline (300 rpm, 0.20 kg/s)", "Recommended"],
         [["Liquid sensible-enthalpy decrease (MJ)", f"{eb.iloc[0].Q_liquid_MJ:.4f}", f"{eb.iloc[1].Q_liquid_MJ:.4f}"],
          ["Heat carried out by the coolant (MJ)", f"{eb.iloc[0].Q_coolant_out_MJ:.4f}", f"{eb.iloc[1].Q_coolant_out_MJ:.4f}"],
          ["Heat stored in the jacket inventory (MJ)", f"{eb.iloc[0].Q_jacket_stored_MJ:.4f}", f"{eb.iloc[1].Q_jacket_stored_MJ:.4f}"],
          ["Residual, trapezoidal rule (J)", f"{eb.iloc[0].residual_trapezoid_J:.2f}", f"{eb.iloc[1].residual_trapezoid_J:.2f}"],
          ["Residual, Simpson's rule (J)", f"{eb.iloc[0].residual_simpson_J:.4f}", f"{eb.iloc[1].residual_simpson_J:.4f}"]])
    jf = t["jf"]
    jrows = []
    for case in ("Coupled baseline", "V3 recommended"):
        sub = jf[jf.case == case].drop_duplicates("n_cells", keep="first").sort_values("n_cells")
        for r in sub.itertuples():
            jrows.append([case, int(r.n_cells), f"{r.T_L_tf_K:.2f}"])
    _tab(G / "tab_jacket.tex", "lrr", ["Case", "Jacket cells", "$T_L(t_f)$ (K)"], jrows)
    mjd = pd.read_csv(D / "model_form/jacket_inventory_isolated.csv")
    _tab(G / "tab_inventory.tex", "rrrr", ["$M_J$ (kg)", "$\\tau_J$ (s)", "$T_L(t_f)$ recommended (K)", "$T_L(t_f)$ baseline (K)"],
         [[f"{r.MJ_kg:.0f}", f"{r.tau_jacket_s:.1f}", f"{r.T_L_tf_recommended_K:.3f}", f"{r.T_L_tf_baseline_K:.3f}"] for r in mjd.itertuples()])
    # compact tables for the two-column paper
    short = {"v1 nominal grid optimum": "V1 grid optimum", "v2/v3 nominal optimum": "Nominal optimum",
             "v1 robust candidate": "V1 robust", "v2 recommended": "V2 recommended", "v3 recommended": "\\textbf{V3 recommended}"}
    _tab(G / "tab_paper_designs.tex", "lrrr", ["Design", "$N$", "$E$ (kWh)", "P(pass) [95\\% CI] (\\%)"],
         [[short[r.design], f"{r.rpm:.0f}", f"{r.mean_energy_kWh:.3f}", f"{100 * r.pass_frac:.1f} [{100 * r.ci_lo:.1f}, {100 * r.ci_hi:.1f}]"]
          for r in leg.itertuples() if r.design != "v1 nominal grid optimum"])
    _tab(G / "tab_paper_scenarios.tex", "lrrrr", ["Closure", "$e_N$", "$e_M$", "Fixed (\\%)", "Adaptive (\\%)"],
         [[r.scenario.split(" (")[0].replace(" closure", "").replace(" scaling", ""), f"{r.eN:.2f}", f"{r.eM:.2f}", f"{100 * r.fixed_recommended_pass:.1f}",
           f"{100 * r.adaptive_pass:.1f}"] for r in sc.itertuples()])
    relax = t["relax"]
    _tab(G / "tab_relax.tex", "rrrrrr", ["Flow limit (kg/s)", "$\\dot m_{cmd}$", "$N$ (rpm)", "Pump (W)", "$\\Delta P$ (bar)", "$E$ (kWh)"],
         [[f2(r.flow_limit_kg_s, 2), f2(r.m_cmd, 2), f2(r.rpm, 0), f2(r.pump_W_at_command, 0), f2(r.loop_dp_bar_at_command, 2), f2(r.expected_energy_kWh, 3)] for r in relax.itertuples()])
    act = t["act"]
    _tab(G / "tab_actuator.tex", "rrrrrr", ["$\\dot m_{cmd}$ (kg/s)", "At limit (\\%)", "Mean actual", "5th pct.", "V2: above limit (\\%)", "V2: max"],
         [[f2(r.m_cmd, 2), f2(100 * r.frac_at_limit, 1), f"{r.mean_actual:.4f}", f"{r.p05:.4f}", f2(100 * r.v2_frac_above_limit, 1), f"{r.v2_max:.3f}"] for r in act.itertuples()])
